CREATE TABLE IF NOT EXISTS account(
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT NOT NULL UNIQUE, salt BYTEA NOT NULL,
 password_hash BYTEA NOT NULL);
CREATE TABLE IF NOT EXISTS session(
 digest BYTEA PRIMARY KEY, account_id INTEGER NOT NULL REFERENCES account(id),
 expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS auth_attempt(
 client TEXT PRIMARY KEY, attempts INTEGER NOT NULL, until INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS project(
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, description TEXT NOT NULL,
 kind TEXT NOT NULL, location TEXT NOT NULL, status TEXT NOT NULL,
 created TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::text, revision INTEGER NOT NULL DEFAULT 0,
 plan TEXT NOT NULL, owner INTEGER REFERENCES account(id));
CREATE TABLE IF NOT EXISTS project_trash(
 project INTEGER PRIMARY KEY REFERENCES project(id),
 deleted_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::text);
CREATE OR REPLACE VIEW project_catalog AS
 SELECT project.*, project_trash.deleted_at
 FROM project LEFT JOIN project_trash ON project_trash.project = project.id;
CREATE TABLE IF NOT EXISTS source(
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project INTEGER NOT NULL REFERENCES project(id),
 name TEXT NOT NULL, digest TEXT NOT NULL, data BYTEA NOT NULL, sheet TEXT NOT NULL,
 options TEXT NOT NULL, mapping TEXT, result TEXT, created TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::text,
 UNIQUE(project, digest, sheet));
CREATE TABLE IF NOT EXISTS source_trash(
 source INTEGER PRIMARY KEY REFERENCES source(id),
 deleted_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::text);
CREATE OR REPLACE VIEW source_catalog AS
 SELECT source.*, source_trash.deleted_at
 FROM source LEFT JOIN source_trash ON source_trash.source = source.id;
CREATE TABLE IF NOT EXISTS report(
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project INTEGER NOT NULL REFERENCES project(id),
 name TEXT NOT NULL, data BYTEA NOT NULL, created TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::text);
CREATE TABLE IF NOT EXISTS template(
 project INTEGER NOT NULL REFERENCES project(id), name TEXT NOT NULL, mapping TEXT NOT NULL,
 PRIMARY KEY(project, name));
CREATE TABLE IF NOT EXISTS event(
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project INTEGER NOT NULL REFERENCES project(id),
 message TEXT NOT NULL, created TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::text);
CREATE INDEX IF NOT EXISTS project_owner ON project(owner);
